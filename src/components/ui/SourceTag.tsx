import clsx from "./clsx";

export type Source = "SIM" | "LIVE" | "REF" | "MODEL" | "USER" | "DEMO";

const STYLE: Record<Source, { c: string; t: string }> = {
  SIM: { c: "text-warn border-warn/40 bg-warn/5", t: "Simulated data — generated by the NEXUS market engine, not real quotes" },
  LIVE: { c: "text-pos border-pos/50 bg-pos/10", t: "Live data from a configured external provider" },
  REF: { c: "text-a3 border-a3/40 bg-a3/5", t: "Reference dataset — approximate historical values bundled with NEXUS; verify before relying on them" },
  MODEL: { c: "text-a1 border-a1/40 bg-a1/5", t: "Model output — computed from your inputs" },
  USER: { c: "text-a2 border-a2/40 bg-a2/5", t: "User-entered data" },
  DEMO: { c: "text-warn border-warn/40 bg-warn/5", t: "Hypothetical demo data" },
};

export function SourceTag({ source, className }: { source: Source; className?: string }) {
  const s = STYLE[source];
  return (
    <span
      title={s.t}
      className={clsx("inline-flex items-center gap-1 border px-1 py-px text-[8.5px] leading-none tracking-[0.14em]", s.c, className)}
    >
      {source === "LIVE" && <span className="h-1 w-1 rounded-full bg-pos nx-blink" />}
      {source}
    </span>
  );
}
